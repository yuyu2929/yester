"""Publish the ``public/`` folder as a static site.

The build lands in ``.yester/site`` which is its own git repository, so
publishing never touches vault history.  With ``publish.remote`` set the
site is pushed to the configured branch (e.g. ``gh-pages``), which turns
any free git host into free website hosting.
"""
from __future__ import annotations

import http.server
import socketserver
import subprocess
import threading
from pathlib import Path

import markdown as md_lib

from .gitops import GitError, Vault

PUBLIC_DIR = "public"
SITE_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
:root {{ --bg:#0f1115; --card:#171a21; --text:#e6e8ee; --muted:#8b93a7; --accent:#7cc4ff; }}
* {{ box-sizing:border-box; }}
body {{ margin:0; font-family:-apple-system,"Segoe UI",Roboto,"Helvetica Neue",Arial,sans-serif;
       background:var(--bg); color:var(--text); line-height:1.65; }}
.wrap {{ max-width:760px; margin:0 auto; padding:48px 20px 96px; }}
header h1 {{ font-size:1.9rem; margin:0 0 4px; }}
header p {{ color:var(--muted); margin:0 0 40px; }}
.card {{ background:var(--card); border:1px solid #232834; border-radius:12px;
        padding:18px 22px; margin:14px 0; }}
.card a {{ color:var(--accent); text-decoration:none; font-weight:600; }}
.card a:hover {{ text-decoration:underline; }}
.card time {{ display:block; color:var(--muted); font-size:.85rem; margin-top:6px; }}
pre {{ background:#0b0d11; border:1px solid #232834; border-radius:8px; padding:14px; overflow:auto; }}
code {{ font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace; font-size:.9em; }}
a {{ color:var(--accent); }}
footer {{ margin-top:64px; color:var(--muted); font-size:.85rem; }}
</style>
</head>
<body><div class="wrap">
{body}
<footer>Generated by Yester — local-first, Git-powered.</footer>
</div></body></html>
"""


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)


def build_site(vault: Vault) -> Path:
    """Render ``public/`` into ``.yester/site``.  Returns the build dir."""
    public = vault.root / PUBLIC_DIR
    if not public.is_dir():
        raise GitError(f"no {PUBLIC_DIR}/ directory in vault")
    site = vault.config.site_dir
    site.mkdir(parents=True, exist_ok=True)
    for stale in site.rglob("*"):
        if stale.is_file():
            stale.unlink()

    pages = []
    for path in sorted(public.rglob("*.md")):
        rel = path.relative_to(public)
        out_rel = rel.with_suffix(".html")
        text = path.read_text(encoding="utf-8")
        html_body = md_lib.markdown(
            text, extensions=["fenced_code", "tables", "toc"]
        )
        title = rel.stem.replace("-", " ").replace("_", " ").title()
        (site / out_rel).parent.mkdir(parents=True, exist_ok=True)
        (site / out_rel).write_text(
            SITE_TEMPLATE.format(title=title, body=html_body), encoding="utf-8"
        )
        pages.append((out_rel.as_posix(), title))

    # copy static assets straight through
    for path in sorted(public.rglob("*")):
        if path.is_file() and path.suffix != ".md":
            rel = path.relative_to(public)
            dest = site / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(path.read_bytes())

    if not (site / "index.html").exists():
        links = "\n".join(
            f'<div class="card"><a href="{href}">{title}</a></div>'
            for href, title in pages
        ) or '<div class="card">Nothing published yet — add Markdown files to <code>public/</code>.</div>'
        (site / "index.html").write_text(
            SITE_TEMPLATE.format(
                title=vault.config.name,
                body=f"<header><h1>{vault.config.name}</h1>"
                     f"<p>Published with Yester</p></header>\n{links}",
            ),
            encoding="utf-8",
        )
    return site


def publish(vault: Vault, push: bool = True) -> str:
    """Build the site and (optionally) push it to ``publish.remote``."""
    pub_cfg = vault.config.data.get("publish", {})
    remote = pub_cfg.get("remote", "")
    branch = pub_cfg.get("branch", "gh-pages")
    if push and not remote:
        raise GitError(
            "publish.remote is not set — add one with "
            "`yester config set publish.remote <url>` or use --no-push"
        )

    site = build_site(vault)
    repo = vault.config.site_dir
    if not (repo / ".git").exists():
        _git(repo, "init", "-b", branch)
        _git(repo, "config", "user.name", f"yester:{vault.config.device}")
        _git(repo, "config", "user.email", "yester@localhost")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-m", "yester(publish): site build", "--allow-empty")
    rev = _git(repo, "rev-parse", "--short", "HEAD").stdout.strip()

    if push:
        if remote not in _git(repo, "remote").stdout.split():
            _git(repo, "remote", "add", "origin", remote)
        proc = _git(repo, "push", "-f", "origin", f"HEAD:{branch}")
        if proc.returncode != 0:
            raise GitError(f"site push failed: {proc.stderr.strip()[:300]}")
    vault.commit(f"publish site {rev}", kind="publish")
    return rev


def preview(vault: Vault, port: int = 8788) -> None:
    """Serve the built site locally."""
    site = build_site(vault)

    class QuietHandler(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *args):  # noqa: D102
            pass

    handler = lambda *a, **kw: QuietHandler(*a, directory=str(site), **kw)
    with socketserver.TCPServer(("127.0.0.1", port), handler) as httpd:
        print(f"preview at http://127.0.0.1:{port} — Ctrl-C to stop")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
